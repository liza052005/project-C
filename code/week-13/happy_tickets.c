#include <stdio.h>

int main() {
    int count = 0;
    
    // Перебираем все возможные номера от 0 до 999999
    for (int num = 0; num <= 999999; num++) {
        // Извлекаем цифры шестизначного номера
        int a = (num / 100000) % 10; // 1-я цифра (сотни тысяч)
        int b = (num / 10000) % 10;  // 2-я цифра (десятки тысяч)
        int c = (num / 1000) % 10;   // 3-я цифра (тысячи)
        int d = (num / 100) % 10;    // 4-я цифра (сотни)
        int e = (num / 10) % 10;     // 5-я цифра (десятки)
        int f = num % 10;            // 6-я цифра (единицы)
        
        // Сумма первых трёх и последних трёх цифр
        int sum1 = a + b + c;
        int sum2 = d + e + f;
        
        // Если суммы равны - билет счастливый
        if (sum1 == sum2) {
            count++;
        }
    }
    
    // Выводим результат
    printf("Количество счастливых билетов: %d\n", count);
    
    return 0;
}